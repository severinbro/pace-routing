#!/usr/bin/env bash
set -Eeuo pipefail
source "$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)/common.sh"

ensure_data_dirs
SENSE_UPLOAD_HOST="${SENSE_UPLOAD_HOST:-pace-sense.local}"
SENSE_TLS_NAME="${SENSE_TLS_NAME:-pace-sense.local}"
SENSE_HTTPS_PORT="${SENSE_HTTPS_PORT:-443}"
SENSE_CA_FILE="${SENSE_CA_FILE:-/run/secrets/sense-ca.crt}"
SENSE_TOKEN_FILE="${SENSE_TOKEN_FILE:-/run/secrets/halo-upload-token}"
UPLOAD_SCAN_SECONDS="${UPLOAD_SCAN_SECONDS:-10}"
UPLOAD_INCLUDE_VIDEO="${UPLOAD_INCLUDE_VIDEO:-false}"
SENSE_UPLOAD_TIMEOUT_SECONDS="${SENSE_UPLOAD_TIMEOUT_SECONDS:-600}"
LIVE_SEGMENTATION_ENABLED="${LIVE_SEGMENTATION_ENABLED:-false}"
LIVE_OUTBOX_MAX_FRAMES="${LIVE_OUTBOX_MAX_FRAMES:-120}"
LIVE_UPLOAD_TIMEOUT_SECONDS="${LIVE_UPLOAD_TIMEOUT_SECONDS:-15}"
LIVE_UPLOAD_REQUIRE_DURABLE_RECEIPT="${LIVE_UPLOAD_REQUIRE_DURABLE_RECEIPT:-false}"
LIVE_UPLOAD_PAUSE_FILE="${LIVE_UPLOAD_PAUSE_FILE:-/etc/halo-camera/config/live-upload.paused}"
HALO_CALIBRATION_FILE="${HALO_CALIBRATION_FILE:-/etc/halo-camera/config/calibration_v5.yaml}"
IMAGE_ROTATION="${IMAGE_ROTATION:-180}"
export DATA_ROOT SENSE_UPLOAD_HOST SENSE_TLS_NAME SENSE_HTTPS_PORT
export SENSE_CA_FILE SENSE_TOKEN_FILE UPLOAD_SCAN_SECONDS UPLOAD_INCLUDE_VIDEO
export SENSE_UPLOAD_TIMEOUT_SECONDS LIVE_SEGMENTATION_ENABLED LIVE_OUTBOX_MAX_FRAMES
export LIVE_UPLOAD_TIMEOUT_SECONDS HALO_CALIBRATION_FILE IMAGE_ROTATION
export LIVE_UPLOAD_REQUIRE_DURABLE_RECEIPT LIVE_UPLOAD_PAUSE_FILE
exec python3 "$SCRIPT_DIR/upload_sessions.py" "$@"
